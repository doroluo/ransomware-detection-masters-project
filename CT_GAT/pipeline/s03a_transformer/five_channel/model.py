class FiveChannelEmbedder(nn.Module):
    """
    Embeds the 5-token tuple (opcode, operand1, operand2, api, behavior)
    per instruction into a single d_model vector.
    """
    def __init__(self, api_vocab_size: int, d_model: int = 64) -> None:
        super().__init__()
        self.d_model = d_model
        if api_vocab_size < tok.FIRST_API_ID:
            api_vocab_size = tok.FIRST_API_ID
            
        self.opcode_embedding = nn.Embedding(OPCODE_VOCAB_SIZE, d_model, padding_idx=0)
        self.operand_embedding = nn.Embedding(OPERAND_VOCAB_SIZE, d_model, padding_idx=0)
        self.api_embedding = nn.Embedding(api_vocab_size, d_model, padding_idx=0)
        self.behavior_embedding = nn.Embedding(tok.BEHAVIOR_VOCAB_SIZE, d_model, padding_idx=0)

    def forward(self, token_ids: torch.Tensor) -> torch.Tensor:
        """
        Args:
            token_ids: Tensor of shape [batch_size, seq_len, 5]
        Returns:
            Tensor of shape [batch_size, seq_len, d_model]
        """
        opcode = token_ids[..., 0].clamp(0, self.opcode_embedding.num_embeddings - 1)
        operand1 = token_ids[..., 1].clamp(0, self.operand_embedding.num_embeddings - 1)
        operand2 = token_ids[..., 2].clamp(0, self.operand_embedding.num_embeddings - 1)
        api = token_ids[..., 3].clamp(min=0, max=self.api_embedding.num_embeddings - 1)
        behavior = token_ids[..., 4].clamp(0, self.behavior_embedding.num_embeddings - 1)

        return (
            self.opcode_embedding(opcode)
            + self.operand_embedding(operand1)
            + self.operand_embedding(operand2)
            + self.api_embedding(api)
            + self.behavior_embedding(behavior)
        )


class Model1TokenSequence(nn.Module):
    """
    Model 1: Token Sequence Classifier
    Processes sequential instruction token IDs generated by preprocess_full.py.
    """
    def __init__(
        self,
        api_vocab_size: int,
        d_model: int = 64,
        nhead: int = 4,
        num_layers: int = 2,
        num_classes: int = 2,
        max_seq_len: int = 128,
        dropout: float = 0.1,
    ) -> None:
        super().__init__()
        self.d_model = d_model
        self.embedder = FiveChannelEmbedder(api_vocab_size=api_vocab_size, d_model=d_model)
        self.pos_encoder = nn.Parameter(torch.zeros(1, max_seq_len, d_model))
        
        encoder_layer = nn.TransformerEncoderLayer(
            d_model=d_model,
            nhead=nhead,
            dim_feedforward=d_model * 4,
            dropout=dropout,
            batch_first=True,
        )
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.classifier = nn.Sequential(
            nn.Linear(d_model, d_model),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(d_model, num_classes),
        )

    def forward(
        self,
        instruction_ids: torch.Tensor,
        padding_mask: torch.Tensor | None = None,
    ) -> torch.Tensor:
        """
        Args:
            instruction_ids: Tensor [batch_size, seq_len, 5]
            padding_mask: BoolTensor [batch_size, seq_len] where True indicates padded tokens
        Returns:
            logits: Tensor [batch_size, num_classes]
        """
        batch_size, seq_len, _ = instruction_ids.shape
        x = self.embedder(instruction_ids)  # [batch_size, seq_len, d_model]
        x = x + self.pos_encoder[:, :seq_len, :]

        # Transformer sequence encoding
        x = self.transformer_encoder(x, src_key_padding_mask=padding_mask)

        # Masked mean pooling across instruction sequence
        if padding_mask is not None:
            mask = (~padding_mask).unsqueeze(-1).float()  # [batch_size, seq_len, 1]
            x_pooled = (x * mask).sum(dim=1) / mask.sum(dim=1).clamp(min=1.0)
        else:
            x_pooled = x.mean(dim=1)

        return self.classifier(x_pooled)


class Model1Dataset(Dataset):
    """
    Loads .pt tensor files produced by preprocess_full.py for Model 1.
    """
    def __init__(self, data_dir: str | Path) -> None:
        raw_files = sorted(glob.glob(str(Path(data_dir) / "*.pt")))
        
        # Exclude saved model/weights artifacts and metadata files
        self.files = [
            f for f in raw_files 
            if not Path(f).name.startswith(("channel_embedder", "meta", "dataset", "vocab", "info"))
        ]

    def __len__(self) -> int:
        return len(self.files)

    def __getitem__(self, idx: int) -> dict[str, torch.Tensor]:
        filepath = self.files[idx]
        sample = torch.load(filepath, weights_only=False)
        
        instruction_ids = sample.get("instruction_ids")
        if instruction_ids is None:
            instruction_ids = sample.get("tokens", sample.get("x"))
            
        if instruction_ids is None:
            raise KeyError(f"File '{filepath}' is missing 'instruction_ids' tensor.")

        label = sample.get("label", sample.get("y", 0))

        return {
            "instruction_ids": instruction_ids,  # Shape: [num_instructions, 5]
            "label": torch.tensor(label, dtype=torch.long),
        }


def model1_collate_fn(batch: list[dict[str, torch.Tensor]], max_instructions: int = 128) -> dict[str, torch.Tensor]:
    """
    Pads variable length instruction sequences in a batch up to max_instructions.
    """
    batch_size = len(batch)
    padded_ids = torch.zeros((batch_size, max_instructions, 5), dtype=torch.long)
    padding_mask = torch.ones((batch_size, max_instructions), dtype=torch.bool)
    labels = torch.zeros(batch_size, dtype=torch.long)

    for idx, item in enumerate(batch):
        ids = item["instruction_ids"]
        seq_len = min(ids.shape[0], max_instructions)
        padded_ids[idx, :seq_len, :] = ids[:seq_len, :]
        padding_mask[idx, :seq_len] = False  # False indicates valid tokens
        labels[idx] = item["label"]

    return {
        "instruction_ids": padded_ids,
        "padding_mask": padding_mask,
        "label": labels,
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run Model 1 (Token Sequence) Inference")
    parser.add_argument("--data-dir", type=str, default=str(tok.PROJECT_ROOT / "processed"), help="Path to processed .pt files")
    parser.add_argument("--batch-size", type=int, default=4, help="Batch size for inference")
    parser.add_argument("--device", type=str, default="cpu", help="Device to run on ('cpu' or 'cuda')")
    parser.add_argument("--max-instructions", type=int, default=128, help="Max sequence length")
    args = parser.parse_args()

    device = torch.device(args.device)

    # Load vocabulary created by preprocess_full.py
    vocab = tok.load_api_vocab(tok.API_VOCAB_PATH)
    api_vocab_size = tok.FIRST_API_ID + len(vocab.names)

    # Initialize Model 1
    model = Model1TokenSequence(
        api_vocab_size=api_vocab_size,
        d_model=64,
        max_seq_len=args.max_instructions,
        num_classes=2,
    ).to(device)

    dataset_path = Path(args.data_dir)
    if not list(dataset_path.glob("*.pt")) and (dataset_path / "cfg_subgraphs").exists():
        dataset_path = dataset_path / "cfg_subgraphs"

    dataset = Model1Dataset(dataset_path)
    if len(dataset) == 0:
        parser.error(f"no preprocessed .pt files in {dataset_path}; pass --data-dir")
    print(f"Loaded {len(dataset)} preprocessed files from: {dataset_path}")

    dataloader = DataLoader(
        dataset,
        batch_size=args.batch_size,
        shuffle=False,
        collate_fn=lambda b: model1_collate_fn(b, max_instructions=args.max_instructions),
    )

    # Batch Inference Loop across all files
    model.eval()
    total_samples = 0

    with torch.no_grad():
        for batch_idx, batch in enumerate(dataloader):
            instruction_ids = batch["instruction_ids"].to(device)
            padding_mask = batch["padding_mask"].to(device)
            labels = batch["label"].to(device)

            logits = model(instruction_ids, padding_mask=padding_mask)
            preds = logits.argmax(dim=-1)

            total_samples += labels.size(0)

            print(
                f"Batch {batch_idx + 1:02d} | "
                f"Logits Shape: {tuple(logits.shape)} | "
                f"Predictions: {preds.tolist()} | "
                f"Targets: {labels.tolist()}"
            )

    print(f"\nCompleted Model 1 inference on {total_samples} samples.")